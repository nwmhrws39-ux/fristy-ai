const dicts = { en, he };

export function translate(lang: "en" | "he", key: TKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useLang(): "en" | "he" {
  return useStore((s) => (s.settings?.ui?.language === "he" ? "he" : "en"));
}

export function useT() {
  const lang = useLang();
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

/** Hebrew text detection for per-message direction. */
export function isRTL(text: string): boolean {
  const m = text.match(/[֐-׿؀-ۿ]|[A-Za-z]/);
  return !!m && /[֐-׿؀-ۿ]/.test(m[0]);
}

